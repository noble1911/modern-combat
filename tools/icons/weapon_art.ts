/**
 * Weapon side-profile art for the unit panel, Close Combat style, drawn from simple shapes in a
 * 120 × 36 box (muzzle to the right, bore axis around y = 14) with shaded material fills and a
 * faint light rim so dark guns read on the dark HUD. Long guns share one scale, so an M240 is
 * visibly longer than a carbine; grenades get a tighter crop.
 *
 * `node tools/icons/build_weapon_icons.ts` (npm run icons) writes each one to
 * public/icons/weapons/<id>.svg — the game only references those files.
 */

/** Material gradients: top highlight → body → shadowed underside. */
const MATS: Record<string, [string, string, string]> = {
  k: ['#5d6264', '#2a2d2f', '#131415'], // black polymer / blued steel
  s: ['#a3a9ab', '#646a6c', '#383b3d'], // bare steel
  f: ['#d3bd92', '#a58f65', '#6c5a3c'], // flat dark earth
  o: ['#848b64', '#5b6140', '#393d27'], // olive drab
  t: ['#bdb68e', '#8e8964', '#5c5840'], // AT4 tube tan
  w: ['#b0703f', '#7b4a28', '#4a2913'], // wood
  g: ['#8cc0e6', '#3d6484', '#1a2d3e'], // optics glass
  b: ['#f0cf72', '#b98f37', '#75561a'], // brass
  r: ['#8a8f7c', '#6a6f5c', '#454937'], // grey-green (smoke canister)
};

type Mat = keyof typeof MATS | 'y' | 'none';

const fill = (m: Mat) => (m === 'y' ? '#e0bf36' : m === 'none' ? 'none' : `url(#${m})`);
const R = (x: number, y: number, w: number, h: number, m: Mat, r = 0) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" fill="${fill(m)}"/>`;
const P = (pts: number[], m: Mat) => `<polygon points="${pts.join(' ')}" fill="${fill(m)}"/>`;
const C = (cx: number, cy: number, r: number, m: Mat) => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${fill(m)}"/>`;
const E = (cx: number, cy: number, rx: number, ry: number, m: Mat) => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill(m)}"/>`;
/** A bar of width w from (x1,y1) to (x2,y2). */
const bar = (x1: number, y1: number, x2: number, y2: number, w: number, m: Mat) => {
  const l = Math.hypot(x2 - x1, y2 - y1) || 1;
  const nx = (-(y2 - y1) / l) * (w / 2);
  const ny = ((x2 - x1) / l) * (w / 2);
  return P([x1 + nx, y1 + ny, x2 + nx, y2 + ny, x2 - nx, y2 - ny, x1 - nx, y1 - ny].map((v) => +v.toFixed(2)), m);
};
const rail = (x0: number, x1: number, y: number) => {
  let s = '';
  for (let x = x0; x < x1; x += 3) s += R(x, y, 1.7, 1.3, 'k');
  return s;
};
const lens = (x: number, y: number, h: number) => R(x, y, 0.9, h, 'g');
/** A riflescope: ocular bell, tube, turret and objective bell (x0 → x1 at height y). */
const scope = (x0: number, x1: number, y: number, big = 1) =>
  R(x0, y - 0.5, 5, 5.5 * big, 'k', 1.5) +
  R(x0 + 4, y, x1 - x0 - 12, 3.6 * big, 'k', 1.5) +
  R((x0 + x1) / 2 - 2, y - 2.5, 4, 3, 'k', 0.8) +
  R(x1 - 9, y - 1.3 * big, 9, 6.4 * big, 'k', 2) +
  lens(x1 - 0.9, y - 0.8 * big, 5.4 * big);
/** A pistol grip whose top front corner is at (x, y). */
const grip = (x: number, y: number, m: Mat = 'k', h = 10) => P([x - 7, y, x, y, x - 2, y + h, x - 9, y + h], m);

